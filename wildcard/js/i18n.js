export const STRINGS = Object.freeze({ en: EN, he: HE });

/** t(lang, key, ...args): replaces %s in order. Unknown key -> the key itself (visible in tests, never silent). */
export function t(lang, key, ...args) {
  const table = STRINGS[lang] || EN;
  let s = table[key] ?? EN[key] ?? key;
  for (const a of args) s = s.replace('%s', String(a));
  return s;
}
